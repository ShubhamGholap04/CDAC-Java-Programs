public class Print_Example2
{
    public static void main(String args[])
    {
        int a=10;
        int b=20;
        //20 is b and a is 10
        System.out.println(b+" is b and "+a+" is a");
        //10+20=30
        System.out.println(a + "+" +b+ "=" + (a+b));
        //a is 10 and 2xa=20
        System.out.println(a+" is a and 2xa="+(a*2));
        //10*20=200
        System.out.println(a+"*"+b+"="+(a*b));
        //using single print line1:a is 10 line2:20 is b
        System.out.println("a is " + a + "\n" + b + " is b ");
    }
}
